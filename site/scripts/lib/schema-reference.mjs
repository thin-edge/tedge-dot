// Render doc/contract/schemas/config.schema.json as the "Configuration file" reference page,
// so the key tables on the site are the schema the SDKs validate against.

const SECTIONS = [
  { heading: '`[connector]`', path: ['properties', 'connector'], intro: 'One per file. Which protocol module runs, and the defaults every device inherits.' },
  { heading: '`[mqtt]`', path: ['properties', 'mqtt'], intro: 'The thin-edge.io broker the connector publishes to. The `read`/`write` CLI ignores it.' },
  { heading: '`[connection]`', path: ['properties', 'connection'], intro: null },
  { heading: '`[[device]]`', path: ['$defs', 'device'], intro: 'One per device. The address is protocol-specific; see the connector reference for its shape.' },
  { heading: '`[[device.point]]`', path: ['$defs', 'point'], intro: 'One per data point, on a device or in a point library.' },
  { heading: '`report` (reporting policy)', path: ['$defs', 'report'], intro: null, link: 'See [Reducing data volume](/tedge-dot/reference/configuration/reducing-data-volume/) and try it in the [report-policy playground](/tedge-dot/tools/report-playground/).' },
  { heading: '`map` (value mapping)', path: ['$defs', 'map'], intro: null, link: 'See [Mapping values](/tedge-dot/reference/configuration/mapping-values/).' },
];

export function renderConfigReference(schema) {
  const out = [
    '---',
    'title: Configuration file',
    `description: ${JSON.stringify('Every key of a tedge-dot connector configuration file, generated from the contract schema.')}`,
    'editUrl: "https://github.com/thin-edge/tedge-dot/edit/main/doc/contract/schemas/config.schema.json"',
    '# Generated by site/scripts/sync-docs.mjs from doc/contract/schemas/config.schema.json.',
    '---',
    '',
    'A connector is configured by one TOML file per protocol in `/etc/tedge/plugins/ot/`. This page is',
    'generated from [`config.schema.json`](https://github.com/thin-edge/tedge-dot/blob/main/doc/contract/schemas/config.schema.json),',
    'the schema both implementations are tested against. Protocol-specific objects (`connection`,',
    '`protocol_address`, a point\'s `address`) are described in each [connector reference](/tedge-dot/reference/connectors/modbus/).',
    '',
    ':::tip',
    'The [config builder](/tedge-dot/tools/config-builder/) fills these in for you and checks the result against the same schema.',
    ':::',
    '',
  ];
  for (const section of SECTIONS) {
    const node = section.path.reduce((n, k) => n?.[k], schema);
    if (!node) continue;
    out.push(`## ${section.heading}`, '');
    const intro = section.intro ?? node.description;
    if (intro) out.push(escapeText(intro), '');
    if (section.link) out.push(section.link, '');
    const props = Object.entries(node.properties ?? {});
    if (props.length) {
      const required = new Set(node.required ?? []);
      out.push('| Key | Type | Default | Description |', '|---|---|---|---|');
      for (const [key, prop] of props) {
        const resolved = prop.$ref ? { ...deref(schema, prop.$ref), ...prop } : prop;
        const name = '`' + key + '`' + (required.has(key) ? ' (required)' : '');
        out.push(`| ${name} | ${typeOf(schema, prop)} | ${defaultOf(resolved)} | ${cell(resolved.description ?? '')} |`);
      }
      out.push('');
    }
    for (const example of node.examples ?? []) {
      out.push('```json', JSON.stringify(example, null, 2), '```', '');
    }
  }
  return out.join('\n');
}

function deref(schema, ref) {
  return ref.replace(/^#\//, '').split('/').reduce((n, k) => n?.[k], schema) ?? {};
}

export function typeOf(schema, prop) {
  if (prop.$ref) {
    const name = prop.$ref.split('/').pop();
    if (name === 'duration' || name === 'report_duration') return 'duration';
    return `\`${name}\` table`;
  }
  if (prop.enum) return prop.enum.map((v) => '`' + JSON.stringify(v).replace(/^"|"$/g, '') + '`').join(' \\| ');
  if (prop.const !== undefined) return '`' + JSON.stringify(prop.const) + '`';
  if (prop.oneOf || prop.anyOf) return (prop.oneOf || prop.anyOf).map((p) => typeOf(schema, p)).join(' or ');
  if (Array.isArray(prop.type)) return prop.type.join(' or ');
  if (prop.type === 'array') {
    const items = prop.items ? typeOf(schema, prop.items) : 'value';
    return `array of ${items}`;
  }
  if (prop.type === 'object') return 'table';
  return prop.type ?? 'any';
}

function defaultOf(prop) {
  if (prop.default === undefined) return '';
  return '`' + (typeof prop.default === 'string' ? prop.default : JSON.stringify(prop.default)) + '`';
}

// `<` outside code spans would be read as HTML.
function escapeText(s) {
  return s
    .split(/(`[^`]*`)/)
    .map((part) => (part.startsWith('`') ? part : part.replace(/</g, '&lt;')))
    .join('');
}

function cell(s) {
  return escapeText(s).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}
