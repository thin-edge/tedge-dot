// The What's new page: every highlight in changes/ under the first published release that
// contained it, newest release first. "Published" means the GitHub release has assets, the
// rule .github/workflows/release.yaml uses: a tag whose release run failed never reached
// users, so its highlights belong to the next release that did.

import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const SEMVER = /^(\d+)\.(\d+)\.(\d+)$/;

export function compareVersions(a, b) {
  const pa = SEMVER.exec(a).slice(1).map(Number);
  const pb = SEMVER.exec(b).slice(1).map(Number);
  for (let i = 0; i < 3; i++) if (pa[i] !== pb[i]) return pa[i] - pb[i];
  return 0;
}

/**
 * Group highlights by release.
 *
 * @param {{file: string, content: string, containedIn: string[]}[]} fragments  in the order they were added
 * @param {string[]} tags        every release tag (X.Y.Z)
 * @param {(tag: string) => boolean} isPublished
 * @returns {{ releases: {tag: string, carries: string[], highlights: object[]}[], unreleased: object[] }}
 */
export function groupByRelease(fragments, tags, isPublished) {
  const ascending = [...tags].filter((t) => SEMVER.test(t)).sort(compareVersions);
  const published = ascending.filter(isPublished);
  const releases = new Map(published.map((t) => [t, { tag: t, carries: [], highlights: [] }]));
  // Each unpublished tag is delivered by the next published one.
  let pending = [];
  for (const t of ascending) {
    if (isPublished(t)) {
      releases.get(t).carries = pending;
      pending = [];
    } else {
      pending.push(t);
    }
  }
  const unreleased = [];
  for (const fragment of fragments) {
    const first = published.find((t) => fragment.containedIn.includes(t));
    if (first) releases.get(first).highlights.push(fragment);
    else unreleased.push(fragment);
  }
  return { releases: [...releases.values()].reverse(), unreleased };
}

/** Render the page. `rewrite(markdown, sourcePath)` fixes a fragment's relative links. */
export function renderWhatsNew({ releases, unreleased }, { repository, dates = {}, backfill = {}, rewrite = (m) => m }) {
  const out = [
    '---',
    "title: What's new",
    'description: "The highlights of every tedge-dot release, newest first."',
    'editUrl: "https://github.com/thin-edge/tedge-dot/tree/main/changes"',
    'tableOfContents: { minHeadingLevel: 2, maxHeadingLevel: 2 }',
    '# Generated by site/scripts/sync-docs.mjs from changes/*.md and git tags.',
    '---',
    '',
    'What changed in each release, for the person upgrading. Every release also has a full',
    `changelog on its [GitHub release](https://github.com/${repository}/releases), and the`,
    '[install guide](/tedge-dot/get-started/install/#upgrading) says what to check when you upgrade.',
    '',
  ];
  const fragmentBody = (f) => stripComments(rewrite(f.content, f.file)).trim();
  if (unreleased.length) {
    out.push('## Unreleased', '', 'On `main`, in the next release.', '');
    for (const f of unreleased) out.push(fragmentBody(f), '');
  }
  for (const r of releases) {
    const extra = backfill[r.tag];
    const url = `https://github.com/${repository}/releases/tag/${r.tag}`;
    out.push(`## ${r.tag}`, '');
    const meta = [dates[r.tag] ? `Released ${dates[r.tag]}` : null, `[GitHub release](${url})`].filter(Boolean);
    out.push(meta.join(' · '), '');
    if (r.carries.length) {
      out.push(`:::note`, `This release also delivers ${listJoin(r.carries)}, which ${r.carries.length > 1 ? 'were' : 'was'} tagged but never published.`, ':::', '');
    }
    const bodies = [...(extra ? [stripComments(extra).trim()] : []), ...r.highlights.map(fragmentBody)];
    if (bodies.length) for (const b of bodies) out.push(b, '');
    else out.push('Fixes and smaller changes: see the changelog on the GitHub release.', '');
  }
  return out.join('\n');
}

function listJoin(items) {
  return items.length > 1 ? `${items.slice(0, -1).join(', ')} and ${items.at(-1)}` : items[0];
}

// A fragment starts with `### `: it stays under its release's `##`. HTML comments are dropped,
// until none is left (removing one can join the halves of another), and an unclosed one is
// shown as text rather than hiding the rest of the page.
export function stripComments(markdown) {
  let prev;
  do {
    prev = markdown;
    markdown = markdown.replace(/<!--[\s\S]*?-->\n*/g, '');
  } while (markdown !== prev);
  return markdown.replace(/<!--/g, '&lt;!--');
}

// --- git and GitHub -------------------------------------------------------------------------

function git(repo, ...args) {
  return execFileSync('git', args, { cwd: repo, encoding: 'utf8' }).trim();
}

/** The highlights in changes/, in the order they were added, with the tags containing each. */
export function readFragments(repo) {
  const log = git(repo, 'log', '--reverse', '--diff-filter=A', '--name-only', '--format=%x00%H', '--', 'changes/*.md');
  const added = new Map();
  for (const entry of log.split('\0').filter(Boolean)) {
    const [sha, ...files] = entry.trim().split('\n');
    for (const f of files.map((s) => s.trim()).filter(Boolean)) if (!added.has(f)) added.set(f, sha);
  }
  // Also count a file that exists but is not committed yet (a pull request in progress).
  for (const f of readdirSync(join(repo, 'changes'))) {
    const path = `changes/${f}`;
    if (f.endsWith('.md') && !added.has(path)) added.set(path, null);
  }
  const fragments = [];
  for (const [file, sha] of added) {
    if (file === 'changes/README.md' || !existsSync(join(repo, file))) continue;
    const containedIn = sha ? git(repo, 'tag', '--contains', sha).split('\n').filter((t) => SEMVER.test(t)) : [];
    fragments.push({ file, content: readFileSync(join(repo, file), 'utf8'), containedIn });
  }
  return fragments;
}

export function readTags(repo) {
  const tags = git(repo, 'tag', '--list').split('\n').filter((t) => SEMVER.test(t));
  const dates = {};
  for (const t of tags) dates[t] = git(repo, 'log', '-1', '--format=%cs', t);
  return { tags, dates };
}

/**
 * Which tags have a GitHub release with assets. Without network access (or when the API
 * refuses), every tag counts as published, with a warning: the page is then only wrong for a
 * tag whose release run failed.
 */
export async function readPublished(repository, tags) {
  const headers = { Accept: 'application/vnd.github+json' };
  if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  try {
    const res = await fetch(`https://api.github.com/repos/${repository}/releases?per_page=100`, { headers });
    if (!res.ok) throw new Error(`GitHub API: HTTP ${res.status}`);
    const releases = await res.json();
    const withAssets = new Set(releases.filter((r) => r.assets?.length > 0).map((r) => r.tag_name));
    return (t) => withAssets.has(t);
  } catch (e) {
    console.warn(`sync-docs: cannot list the GitHub releases (${e.message}); treating every tag as published`);
    return () => true;
  }
}

export function readBackfill(dir) {
  if (!existsSync(dir)) return {};
  return Object.fromEntries(
    readdirSync(dir)
      .filter((f) => f.endsWith('.md'))
      .map((f) => [f.replace(/\.md$/, ''), readFileSync(join(dir, f), 'utf8')]),
  );
}

export function isShallow(repo) {
  return git(repo, 'rev-parse', '--is-shallow-repository') === 'true';
}
