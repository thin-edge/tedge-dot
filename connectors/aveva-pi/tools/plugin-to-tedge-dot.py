#!/usr/bin/env python3
"""Turn a thin-edge-aveva-pi-connector configuration into a tedge-dot `aveva-pi` connector config.

    plugin-to-tedge-dot.py --pi-config config/pi_config.json --datapoints config/datapoints.json \\
        --device pi-plant1 [--data-server PISRV01] [--ca-file pi-ca.pem] > aveva-pi.toml

The community plugin lists tag names only. tedge-dot needs a datatype for each point, so this
script asks the PI Web API for each tag's point type (one lookup per tag, once) and writes the
default datatype of doc/connectors/aveva-pi-connector-spec.md §4. Point ids are the tag names with
`.` replaced by `_`, which is how the plugin named its Cumulocity series, so existing series keep
their names.

The password is NOT written to the output: put it in the file the output names
(`password_file`). Python standard library only.
"""
import argparse
import base64
import json
import ssl
import sys
import urllib.error
import urllib.parse
import urllib.request

DATATYPES = {
    "Float16": "float32",
    "Float32": "float32",
    "Float64": "float64",
    "Int16": "int16",
    "Int32": "int32",
    "Digital": "string",
    "String": "string",
    "Timestamp": "string",
}


def toml_str(value):
    """A TOML basic string. JSON's escapes are a subset of TOML's, so `DOMAIN\\user` and tag
    names with quotes stay valid."""
    return json.dumps(value, ensure_ascii=False)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--pi-config", required=True, help="the plugin's pi_config.json")
    ap.add_argument("--datapoints", required=True, help="the plugin's datapoints.json (a list of tag names)")
    ap.add_argument("--device", required=True, help="the tedge-dot device name (the child device in Cumulocity)")
    ap.add_argument("--data-server", help="the PI Data Archive; default: the server's first data server")
    ap.add_argument("--ca-file", help="CA bundle for the PI Web API certificate")
    ap.add_argument("--insecure", action="store_true", help="skip TLS verification for these lookups only")
    ap.add_argument("--password-file", default="/etc/tedge/plugins/ot/secrets/aveva-pi.password",
                    help="the password file the generated config names")
    args = ap.parse_args(argv)

    with open(args.pi_config) as f:
        pi = json.load(f)
    with open(args.datapoints) as f:
        tags = json.load(f)
    base = pi["PI_URL"].rstrip("/")
    user = pi.get("PI_USER", "")
    password = base64.b64decode(pi.get("PI_PASSWORD", "")).decode() if pi.get("PI_PASSWORD") else ""

    # Plain HTTP (a test bench) needs no TLS context, nor the CA file to exist on this machine.
    ctx = ssl.create_default_context(cafile=args.ca_file) if base.startswith("https:") else None
    if ctx and args.insecure:
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE
    auth = "Basic " + base64.b64encode(f"{user}:{password}".encode()).decode()

    def get(endpoint, **query):
        url = f"{base}/{endpoint}?{urllib.parse.urlencode(query)}"
        req = urllib.request.Request(url, headers={"Authorization": auth})
        with urllib.request.urlopen(req, context=ctx, timeout=30) as r:
            return json.load(r)

    def fail(what, e):
        sys.exit(f"{what}: {e}")

    server = args.data_server
    if not server:
        try:
            servers = get("dataservers", selectedFields="Items.Name").get("Items", [])
        except (urllib.error.URLError, OSError) as e:
            fail(f"cannot list the data servers of {base}", e)
        if not servers:
            sys.exit("the PI Web API lists no data server; pass --data-server")
        server = servers[0]["Name"]

    out = [
        "# Generated by connectors/aveva-pi/tools/plugin-to-tedge-dot.py from",
        f"# {args.pi_config} and {args.datapoints}.",
        "[connector]",
        'protocol      = "aveva-pi"',
        'service_name  = "tedge-dot-aveva-pi"',
        f'poll_interval = "{int(pi.get("POLL_INTERVAL", 60))}s"',
        'output        = "measurements"',
        "",
        "[connection]",
        f'auth = {{ method = "basic", username = {toml_str(user)}, '
        f'password_file = {toml_str(args.password_file)} }}',
    ]
    if args.ca_file:
        out.append(f'tls  = {{ ca_file = {toml_str(args.ca_file)} }}')
    out += [
        "",
        "[[device]]",
        f'name             = {toml_str(args.device)}',
        f'protocol_address = {{ base_url = {toml_str(base)}, data_server = {toml_str(server)} }}',
    ]
    seen = {}
    missing = []
    for tag in tags:
        point_id = tag.replace(".", "_")
        if point_id in seen and seen[point_id] != tag:
            print(f"warning: tags '{seen[point_id]}' and '{tag}' both become point id '{point_id}'; "
                  f"rename one", file=sys.stderr)
        seen.setdefault(point_id, tag)
        try:
            p = get("points", path=f"\\\\{server}\\{tag}", selectedFields="PointType;EngineeringUnits")
        except urllib.error.HTTPError as e:
            # Only "no such point" is per tag; anything else (401, 5xx) fails every lookup.
            if e.code != 404:
                fail(f"looking up {tag}", e)
            missing.append(tag)
            print(f"warning: {tag}: not found on {server}; written as float64", file=sys.stderr)
            p = {}
        except (urllib.error.URLError, OSError) as e:
            fail(f"looking up {tag}", e)
        datatype = DATATYPES.get(p.get("PointType", ""), "float64")
        out += [
            "",
            "  [[device.point]]",
            f'  id       = {toml_str(point_id)}',
            f'  datatype = "{datatype}"',
            f'  address  = {{ tag = {toml_str(tag)} }}',
        ]
    print("\n".join(out))
    print(f"{len(tags)} points written ({len(missing)} not found on {server}). "
          f"Now put the password in {args.password_file} (mode 0600, owner tedge).", file=sys.stderr)


if __name__ == "__main__":
    main()
