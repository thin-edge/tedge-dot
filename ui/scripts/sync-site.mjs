// Brings the docs site's connector-file model into the UI, so the repository holds one copy of it:
// the config builder's module (site/src/lib/config-builder.ts) with its protocol shapes
// (site/src/data/protocols.json) and the contract schemas (doc/contract/schemas), the forms' option
// lists (site/src/lib/form-options.ts) and the field help (site/src/lib/help.ts). The copies go to
// src/generated/, which is not committed. Run before every build and test (see package.json).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ui = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(ui, '..');
const out = join(ui, 'src', 'generated');
mkdirSync(out, { recursive: true });

const header = (source) =>
  `// Generated by scripts/sync-site.mjs from ${source}. Do not edit; edit the source.\n`;

for (const [source, target] of [
  ['doc/contract/schemas/config.schema.json', 'config.schema.json'],
  ['doc/contract/schemas/point-library.schema.json', 'point-library.schema.json'],
  ['site/src/data/protocols.json', 'protocols.json'],
]) {
  writeFileSync(join(out, target), readFileSync(join(repo, source)));
}

const builder = 'site/src/lib/config-builder.ts';
let code = readFileSync(join(repo, builder), 'utf8');
const imports = [
  ["'../../../doc/contract/schemas/config.schema.json'", "'./config.schema.json'"],
  ["'../../../doc/contract/schemas/point-library.schema.json'", "'./point-library.schema.json'"],
  ["'../data/protocols.json'", "'./protocols.json'"],
];
for (const [from, to] of imports) {
  if (!code.includes(from)) {
    throw new Error(`${builder} no longer imports ${from}; update scripts/sync-site.mjs`);
  }
  code = code.replace(from, to);
}
writeFileSync(join(out, 'config-builder.ts'), header(builder) + code);

// Modules without imports, copied as they are.
for (const source of ['site/src/lib/form-options.ts', 'site/src/lib/help.ts']) {
  const text = readFileSync(join(repo, source), 'utf8');
  if (/^\s*import\s/m.test(text)) {
    throw new Error(`${source} imports other modules now; update scripts/sync-site.mjs`);
  }
  writeFileSync(join(out, source.split('/').pop()), header(source) + text);
}
console.log(`synced the site's connector-file model into ${out}`);
