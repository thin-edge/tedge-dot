// Brings the docs site's connector-file validation into the UI, so the repository holds one copy
// of the rules: the config builder's module (site/src/lib/config-builder.ts), its protocol shapes
// (site/src/data/protocols.json) and the contract schemas (doc/contract/schemas). The copies go to
// src/generated/, which is not committed. Run before every build and test (see package.json).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ui = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(ui, '..');
const out = join(ui, 'src', 'generated');
mkdirSync(out, { recursive: true });

const header = (source) =>
  `// Generated by scripts/sync-validation.mjs from ${source}. Do not edit; edit the source.\n`;

for (const [source, target] of [
  ['doc/contract/schemas/config.schema.json', 'config.schema.json'],
  ['doc/contract/schemas/point-library.schema.json', 'point-library.schema.json'],
  ['site/src/data/protocols.json', 'protocols.json'],
]) {
  writeFileSync(join(out, target), readFileSync(join(repo, source)));
}

const builder = 'site/src/lib/config-builder.ts';
let code = readFileSync(join(repo, builder), 'utf8');
const imports = [
  ["'../../../doc/contract/schemas/config.schema.json'", "'./config.schema.json'"],
  ["'../../../doc/contract/schemas/point-library.schema.json'", "'./point-library.schema.json'"],
  ["'../data/protocols.json'", "'./protocols.json'"],
];
for (const [from, to] of imports) {
  if (!code.includes(from)) {
    throw new Error(`${builder} no longer imports ${from}; update scripts/sync-validation.mjs`);
  }
  code = code.replace(from, to);
}
writeFileSync(join(out, 'config-builder.ts'), header(builder) + code);
console.log(`synced validation into ${out}`);
